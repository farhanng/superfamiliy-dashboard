// Get menus by category
export function getMenusByCategory(category) {
  return SAMPLE_MENUS.filter(m => m.category === category)
}

// Get random menus
export function getRandomMenus(count = 5) {
  const shuffled = [...SAMPLE_MENUS].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, count)
}

// Search menus
export function searchMenus(query) {
  const q = query.toLowerCase()
  return SAMPLE_MENUS.filter(m => 
    m.name.toLowerCase().includes(q) || 
    m.tags.some(t => t.includes(q))
  )
}

